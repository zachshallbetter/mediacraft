//! Contact Sheet & Media Overview Export Engine (FEATURES.md:L42).
//!
//! Generates browsable, printable, and client-ready asset overview manifests
//! and standalone HTML contact sheets without external runtime dependencies.

use crate::MediaAsset;

/// Options for configuring contact sheet output.
#[derive(Debug, Clone)]
pub struct ContactSheetOptions {
    pub title: String,
    pub project_name: String,
    pub include_technical_metadata: bool,
    pub include_tags: bool,
    pub columns: usize,
}

impl Default for ContactSheetOptions {
    fn default() -> Self {
        Self {
            title: "MediaCraft Asset Contact Sheet".to_string(),
            project_name: "Summer Campaign 2026".to_string(),
            include_technical_metadata: true,
            include_tags: true,
            columns: 4,
        }
    }
}

/// Generates contact sheet reports in multiple formats.
pub struct ContactSheetGenerator;

impl ContactSheetGenerator {
    /// Generates a self-contained, beautifully styled responsive dark HTML contact sheet.
    pub fn generate_html(assets: &[MediaAsset], options: &ContactSheetOptions) -> String {
        let mut html = String::new();
        html.push_str("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n");
        html.push_str("<meta charset=\"utf-8\">\n<meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">\n");
        html.push_str(&format!(
            "<title>{} — {}</title>\n",
            options.title, options.project_name
        ));
        html.push_str("<style>\n");
        html.push_str("body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; background: #0e1115; color: #ebf2fa; margin: 0; padding: 24px; }\n");
        html.push_str(".header { border-bottom: 1px solid #2d3644; padding-bottom: 16px; margin-bottom: 24px; display: flex; justify-content: space-between; align-items: baseline; }\n");
        html.push_str(".title { font-size: 22px; font-weight: 700; color: #50beff; }\n");
        html.push_str(".subtitle { font-size: 13px; color: #8fa0b5; }\n");
        html.push_str(".grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(260px, 1fr)); gap: 16px; }\n");
        html.push_str(".card { background: #161b22; border: 1px solid #2d3644; border-radius: 6px; overflow: hidden; padding: 12px; box-sizing: border-box; }\n");
        html.push_str(".thumb { width: 100%; height: 140px; background: #090c10; border-radius: 4px; display: flex; align-items: center; justify-content: center; font-size: 11px; color: #50beff; margin-bottom: 10px; border: 1px solid #21262d; font-family: monospace; }\n");
        html.push_str(".filename { font-size: 13px; font-weight: 600; margin-bottom: 4px; overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }\n");
        html.push_str(".meta { font-size: 11px; color: #8fa0b5; margin-bottom: 2px; }\n");
        html.push_str(".badge { display: inline-block; padding: 2px 6px; font-size: 10px; font-weight: 600; border-radius: 3px; background: #1f2733; color: #50beff; margin-right: 4px; margin-top: 6px; }\n");
        html.push_str(".rating { color: #f5a623; font-size: 11px; margin-top: 4px; }\n");
        html.push_str("</style>\n</head>\n<body>\n");

        html.push_str("<div class=\"header\">\n");
        html.push_str(&format!("  <div><div class=\"title\">{}</div><div class=\"subtitle\">Project: {} • Total Assets: {}</div></div>\n", options.title, options.project_name, assets.len()));
        html.push_str(
            "  <div class=\"subtitle\">Generated by MediaCraft Filesystem Workspace</div>\n",
        );
        html.push_str("</div>\n\n");

        html.push_str("<div class=\"grid\">\n");
        for asset in assets {
            html.push_str("  <div class=\"card\">\n");
            let res = asset
                .video
                .as_ref()
                .map(|v| format!("{}×{}", v.width, v.height))
                .unwrap_or_else(|| asset.kind.label().to_string());
            let codec = asset
                .video
                .as_ref()
                .map(|v| v.codec.as_str())
                .or_else(|| asset.audio.as_ref().map(|a| a.codec.as_str()))
                .unwrap_or("Standard");

            html.push_str(&format!(
                "    <div class=\"thumb\">[ {} • {} ]</div>\n",
                asset.kind.label(),
                res
            ));
            html.push_str(&format!(
                "    <div class=\"filename\" title=\"{}\">{}</div>\n",
                asset.filename, asset.filename
            ));
            html.push_str(&format!(
                "    <div class=\"meta\">{} • {} • {}</div>\n",
                asset.formatted_size(),
                asset.formatted_duration(),
                codec
            ));
            html.push_str(&format!(
                "    <div class=\"meta\">TC: {}</div>\n",
                asset.timecode_start
            ));

            if options.include_tags && !asset.tags.is_empty() {
                html.push_str("    <div>\n");
                for tag in &asset.tags {
                    html.push_str(&format!("      <span class=\"badge\">#{}</span>\n", tag));
                }
                html.push_str("    </div>\n");
            }

            let stars = "★".repeat(asset.rating as usize);
            if !stars.is_empty() {
                html.push_str(&format!("    <div class=\"rating\">{}</div>\n", stars));
            }

            html.push_str("  </div>\n");
        }
        html.push_str("</div>\n\n</body>\n</html>\n");

        html
    }

    /// Generates a plain text tabular summary suitable for logs, manifests, and CLI outputs.
    pub fn generate_text_manifest(assets: &[MediaAsset], project_name: &str) -> String {
        let mut out = String::new();
        out.push_str(&format!(
            "MEDIACRAFT CONTACT SHEET MANIFEST — {}\n",
            project_name
        ));
        out.push_str(&"=".repeat(88));
        out.push('\n');
        out.push_str(&format!(
            "{:<28} {:<10} {:<12} {:<10} {:<14} {:<10}\n",
            "FILENAME", "KIND", "SIZE", "DURATION", "TIMECODE", "STARS"
        ));
        out.push_str(&"-".repeat(88));
        out.push('\n');

        for a in assets {
            let stars = "*".repeat(a.rating as usize);
            out.push_str(&format!(
                "{:<28} {:<10} {:<12} {:<10} {:<14} {:<10}\n",
                if a.filename.len() > 27 {
                    format!("{}...", &a.filename[..24])
                } else {
                    a.filename.clone()
                },
                a.kind.label(),
                a.formatted_size(),
                a.formatted_duration(),
                a.timecode_start,
                stars
            ));
        }
        out.push_str(&"=".repeat(88));
        out.push('\n');
        out.push_str(&format!("Total Count: {} media asset(s)\n", assets.len()));
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::MediaKind;
    use std::path::PathBuf;

    #[test]
    fn test_contact_sheet_generation() {
        let assets = vec![MediaAsset {
            id: "sample_1".to_string(),
            path: PathBuf::from("/Media/A001_C001.mov"),
            filename: "A001_C001.mov".to_string(),
            file_size_bytes: 4_200_000_000,
            kind: MediaKind::Video,
            duration_secs: Some(30.0),
            timecode_start: "01:00:00:00".to_string(),
            video: None,
            audio: None,
            camera_model: None,
            date_created: "2026-10-12".to_string(),
            geo_location: None,
            rating: 5,
            tags: vec!["hero".to_string(), "master".to_string()],
            has_proxy: true,
            needs_transcode: false,
            is_offline: false,
        }];

        let html = ContactSheetGenerator::generate_html(&assets, &ContactSheetOptions::default());
        assert!(html.contains("MediaCraft Asset Contact Sheet"));
        assert!(html.contains("A001_C001.mov"));
        assert!(html.contains("#hero"));

        let manifest = ContactSheetGenerator::generate_text_manifest(&assets, "Campaign Alpha");
        assert!(manifest.contains("Campaign Alpha"));
        assert!(manifest.contains("A001_C001.mov"));
        assert!(manifest.contains("Total Count: 1 media asset(s)"));
    }
}
